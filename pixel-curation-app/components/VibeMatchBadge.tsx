// components/VibeMatchBadge.tsx
"use client";

import { useMemo } from 'react';
import { motion } from 'framer-motion';
import { Sparkles } from 'lucide-react';

interface VibeMatchProps {
  visitorApiIds: string[];
  ownerApiIds: string[];
}

export default function VibeMatchBadge({ visitorApiIds, ownerApiIds }: VibeMatchProps) {
  // 1. The Client-Side Algorithm (Memoized for performance)
  const matchPercentage = useMemo(() => {
    if (!visitorApiIds.length || !ownerApiIds.length) return 0;

    const visitorSet = new Set(visitorApiIds);
    const ownerSet = new Set(ownerApiIds);

    // Find shared items
    const intersection = [...visitorSet].filter(id => ownerSet.has(id));

    // Overlap Coefficient calculation
    const smallestLibrarySize = Math.min(visitorSet.size, ownerSet.size);
    const score = (intersection.length / smallestLibrarySize) * 100;

    return Math.round(score);
  }, [visitorApiIds, ownerApiIds]);

  // Don't render if there's no data or it's the user's own profile
  if (matchPercentage === 0) return null;

  // Determine badge text based on score
  let vibeText = "Different Wavelengths";
  if (matchPercentage >= 50) vibeText = "Solid Overlap";
  if (matchPercentage >= 75) vibeText = "Vibe Synergists";
  if (matchPercentage >= 90) vibeText = "Taste Twins 👯";

  return (
    <motion.div 
      initial={{ scale: 0.8, opacity: 0, y: 10 }}
      animate={{ scale: 1, opacity: 1, y: 0 }}
      transition={{ type: 'spring', stiffness: 300, damping: 20 }}
      // Styling utilizes the dynamic CSS variables generated by your ThemeSync
      className="inline-flex items-center gap-2 px-4 py-2 rounded-full border border-[var(--theme-outline,gray)] bg-[var(--theme-surface,#27272a)] text-[var(--theme-primary,white)] shadow-lg"
    >
      <Sparkles size={16} className="text-[var(--theme-secondary,yellow)]" />
      <span className="font-bold font-sans">{matchPercentage}% Match</span>
      <span className="text-sm opacity-80 border-l border-[var(--theme-outline,gray)] pl-2 ml-1">
        {vibeText}
      </span>
    </motion.div>
  );
}